"""Jarod-OS rename, phase 5 (docs/RENAME-PLAN-JAROD-OS.md): the bridge's folder in the Hermes home is ``jarod-os``.

The older ``herald-os`` folder is COPIED, never moved: an earlier version still finds its data there. The copy is made once, into a
temporary folder renamed into place, so the shell and the bridge starting together cannot both write it; the plugin copy
(``bridge-plugin``) is regenerated by the app and never carried over. The shell does the same (apps/desktop/electron/migrate.ts)."""

from __future__ import annotations

import importlib

import pytest


@pytest.fixture
def util(plugin):
    return importlib.import_module(plugin.__name__ + ".bridge.util")


def write(path, text="x"):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def test_the_folder_has_the_new_name(util, isolated_home):
    assert util.data_dir() == isolated_home / "jarod-os"


def test_the_older_folder_is_copied_and_left_as_it_was(util, isolated_home):
    old = isolated_home / "herald-os"
    write(old / "permissions.yaml", "tiers: {}")
    write(old / "audit.jsonl", '{"tool": "system_info"}\n')
    write(old / "bridge-plugin" / "plugin.yaml", "name: herald-os-bridge")

    new = util.data_dir()

    assert (new / "permissions.yaml").read_text(encoding="utf-8") == "tiers: {}"
    assert (new / "audit.jsonl").read_text(encoding="utf-8") == '{"tool": "system_info"}\n'
    assert not (new / "bridge-plugin").exists()
    assert (new / ".copied-from-herald-os").read_text(encoding="utf-8")[:4].isdigit()
    assert (old / "permissions.yaml").read_text(encoding="utf-8") == "tiers: {}"
    assert (old / "bridge-plugin" / "plugin.yaml").exists()


def test_an_existing_new_folder_is_never_overwritten(util, isolated_home):
    write(isolated_home / "herald-os" / "permissions.yaml", "old")
    write(isolated_home / "jarod-os" / "permissions.yaml", "new")

    assert (util.data_dir() / "permissions.yaml").read_text(encoding="utf-8") == "new"


def test_the_copy_happens_once_and_leaves_no_half_folder(util, isolated_home):
    write(isolated_home / "herald-os" / "permissions.yaml", "first")
    util.data_dir()
    write(isolated_home / "herald-os" / "permissions.yaml", "changed later by an older version")

    assert (util.data_dir() / "permissions.yaml").read_text(encoding="utf-8") == "first"
    assert sorted(p.name for p in isolated_home.iterdir() if p.name.startswith(("jarod-os", "herald-os"))) == ["herald-os", "jarod-os"]


def test_losing_the_race_to_another_process_keeps_its_copy(util, isolated_home, monkeypatch):
    """The shell renamed its own copy into place between our copy and our rename: ours is thrown away, theirs kept."""
    write(isolated_home / "herald-os" / "permissions.yaml", "ours")
    real_copytree = util.shutil.copytree

    def copy_then_lose(src, dst, **kwargs):
        result = real_copytree(src, dst, **kwargs)
        write(isolated_home / "jarod-os" / "permissions.yaml", "theirs")
        return result

    monkeypatch.setattr(util.shutil, "copytree", copy_then_lose)

    assert (util.data_dir() / "permissions.yaml").read_text(encoding="utf-8") == "theirs"
    assert not [p for p in isolated_home.iterdir() if ".partial-" in p.name]


def test_no_older_folder_means_nothing_is_copied_or_invented(util, isolated_home):
    assert util.data_dir().name == "jarod-os"
    assert not (isolated_home / "herald-os").exists()
    assert not (isolated_home / "jarod-os" / ".copied-from-herald-os").exists()


def test_the_shared_endpoint_is_read_from_the_new_folder_first(plugin, isolated_home):
    ui = importlib.import_module(plugin.__name__ + ".bridge.ui")
    write(isolated_home / "herald-os" / "control.json", '{"socket": "pipe://old", "token": "old-token"}')
    assert ui.shared_endpoint() == ("pipe://old", "old-token"), "a shell from before the rename is still found"
    write(isolated_home / "jarod-os" / "control.json", '{"socket": "pipe://new", "token": "new-token"}')
    assert ui.shared_endpoint() == ("pipe://new", "new-token")
